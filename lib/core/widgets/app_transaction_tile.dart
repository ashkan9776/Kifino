import 'package:flutter/material.dart';

import '../../app/theme/app_colors.dart';
import '../../app/theme/app_spacing.dart';
import '../../app/theme/app_typography.dart';
import '../utils/date_utils.dart';
import '../utils/icon_utils.dart';
import '../../features/transactions/domain/entities/transaction_entity.dart';
import 'app_card.dart';
import 'app_money_text.dart';

class AppTransactionTile extends StatelessWidget {
  final TransactionEntity transaction;
  final VoidCallback? onTap;
  final VoidCallback? onDelete;

  /// Inside a day-grouped list the day is already the header, so the row
  /// shows the time instead of a relative date.
  final bool showTimeOnly;

  const AppTransactionTile({
    super.key,
    required this.transaction,
    this.onTap,
    this.onDelete,
    this.showTimeOnly = false,
  });

  /// Generic words the add screen used to save when the note was empty.
  static const _genericTitles = {'هزینه', 'درآمد', 'انتقال', 'تراکنش'};

  /// The most informative title: the user's text, else the category.
  String get _title {
    final d = transaction.description.trim();
    final category = transaction.categoryName;
    if ((d.isEmpty || _genericTitles.contains(d)) && category != null) {
      return category;
    }
    return d.isNotEmpty ? d : (category ?? 'تراکنش');
  }

  @override
  Widget build(BuildContext context) {
    final colors = context.customColors;
    final isDark = Theme.of(context).brightness == Brightness.dark;

    final categoryColor = _parseHex(transaction.categoryColorHex);
    final (iconData, iconColor) = switch (transaction.type) {
      TransactionType.income => (
        transaction.categoryIconCodePoint != null
            ? IconUtils.getIconData(transaction.categoryIconCodePoint!)
            : Icons.south_west_rounded,
        categoryColor ?? colors.income,
      ),
      TransactionType.expense => (
        transaction.categoryIconCodePoint != null
            ? IconUtils.getIconData(transaction.categoryIconCodePoint!)
            : Icons.north_east_rounded,
        categoryColor ?? colors.expense,
      ),
      TransactionType.transfer => (Icons.swap_horiz_rounded, colors.transfer),
      TransactionType.debtPayment => (
        Icons.handshake_outlined,
        isDark ? AppColors.debtOrangeDark : AppColors.debtOrangeLight,
      ),
      TransactionType.receivablePayment => (
        Icons.handshake_outlined,
        colors.receivable,
      ),
      _ => (Icons.tune_rounded, Theme.of(context).colorScheme.primary),
    };
    final secondary = colors.textSecondary;
    final meta = [
      if (transaction.accountName != null) transaction.accountName!,
      showTimeOnly
          ? AppDateFormatter.formatTime(transaction.date)
          : AppDateFormatter.formatRelative(transaction.date, locale: 'fa'),
    ].join('  ·  ');

    final tile = Material(
      color: Colors.transparent,
      child: InkWell(
        onTap: onTap,
        borderRadius: AppSpacing.borderRadiusMd,
        child: Padding(
          padding: const EdgeInsets.symmetric(
            horizontal: AppSpacing.md,
            vertical: 12,
          ),
          child: Row(
            children: [
              AppIconBadge(icon: iconData, color: iconColor),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      children: [
                        Flexible(
                          child: Text(
                            _title,
                            style: AppTypography.titleSmall.copyWith(
                              color: colors.textPrimary,
                            ),
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                          ),
                        ),
                        if (transaction.isAutoGenerated ||
                            transaction.recurringRuleId != null) ...[
                          const SizedBox(width: 6),
                          Icon(
                            transaction.recurringRuleId != null
                                ? Icons.event_repeat_rounded
                                : Icons.link_rounded,
                            size: 14,
                            color: colors.textTertiary,
                          ),
                        ],
                      ],
                    ),
                    const SizedBox(height: 2),
                    Text(
                      meta,
                      style: AppTypography.bodySmall.copyWith(color: secondary),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                    ),
                  ],
                ),
              ),
              const SizedBox(width: 8),
              AppMoneyText(
                money: transaction.amount,
                sign: transaction.type == TransactionType.income
                    ? MoneyDisplaySign.positiveNegative
                    : (transaction.type == TransactionType.expense
                          ? MoneyDisplaySign.negativeOnly
                          : MoneyDisplaySign.none),
                style: AppTypography.moneyTile.copyWith(
                  color: colors.textPrimary,
                ),
                colorCode: true,
                usePersianDigits: true,
              ),
            ],
          ),
        ),
      ),
    );

    if (onDelete != null) {
      return Dismissible(
        key: Key(transaction.id),
        direction: DismissDirection.endToStart,
        background: Container(
          alignment: Alignment.centerRight,
          padding: const EdgeInsets.symmetric(horizontal: AppSpacing.lg),
          decoration: BoxDecoration(
            color: colors.expense,
            borderRadius: AppSpacing.borderRadiusMd,
          ),
          child: const Icon(Icons.delete_outline_rounded, color: Colors.white),
        ),
        onDismissed: (_) => onDelete!(),
        child: tile,
      );
    }

    return tile;
  }
}

Color? _parseHex(String? hex) {
  if (hex == null || hex.isEmpty) return null;
  final cleaned = hex.replaceFirst('#', '');
  final value = int.tryParse(
    cleaned.length == 6 ? 'FF$cleaned' : cleaned,
    radix: 16,
  );
  return value == null ? null : Color(value);
}
